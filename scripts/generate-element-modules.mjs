import { writeFile } from 'node:fs/promises'

const generatedNotice = '// Auto-generated by scripts/generate-element-modules.mjs. Do not edit by hand.'

const elementsModule = `${generatedNotice}
import rawElements from './elements.json'
import {
  CATEGORY_COLORS,
  CATEGORY_LABELS,
  type Element,
  type ElementCategory,
  type Phase,
} from './schema'

export { CATEGORY_COLORS, CATEGORY_LABELS }
export type { Element, ElementCategory, Phase }

export const elements = rawElements as Element[]

export const elementsByNumber: Record<number, Element> = Object.fromEntries(
  elements.map((element) => [element.n, element]),
)

export const elementsBySymbol: Record<string, Element> = Object.fromEntries(
  elements.map((element) => [element.sym, element]),
)
`

const elementL3Module = `${generatedNotice}
import rawElementL3Data from './element-l3-data.json'
import type { ElementL3Record } from './schema'

export type { ElementL3Record }

export const ELEMENT_L3_DATA = rawElementL3Data as Record<number, ElementL3Record>
`

await writeFile(new URL('../src/data/elements/elements.ts', import.meta.url), elementsModule)
await writeFile(
  new URL('../src/data/elements/element-l3-data.ts', import.meta.url),
  elementL3Module,
)

